#!/usr/bin/env python3
"""CLS-01 step 6: dataset statistics by class, window size, lighting, mannequin type, position and split.

  python tools/dataset/stats.py <root> [--splits <root>/splits.json] [--doc docs/dataset.md]

Prints Markdown; with --doc it overwrites the part between <!-- dataset:begin --> and <!-- dataset:end --> of the document.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter, defaultdict
from pathlib import Path

from common import utf8_console, LABELS, SPLITS, Sample, all_samples, load_root, read_json

BEGIN = "<!-- dataset:begin -->"
END = "<!-- dataset:end -->"

DIMENSIONS: list[tuple[str, str, tuple[str, ...]]] = [
    ("By window size (short side px)", "sizeClass", ("small", "medium", "large")),
    ("By lighting", "lighting", ("normal", "bright", "dim", "backlit")),
    ("By mannequin type", "mannequinType", ("none", "plastic", "fabric", "silicone")),
    ("By window position", "position", ("center", "edge")),
]


def table(header: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(lines)


def cross(samples: list[Sample], key: str, values: tuple[str, ...]) -> str:
    counts: dict[str, Counter] = defaultdict(Counter)
    extra: set[str] = set()
    for s in samples:
        v = s.field(key)
        counts[s.label][v] += 1
        if v not in values:
            extra.add(v)
    cols = list(values) + sorted(extra)
    rows: list[list[object]] = []
    for label in LABELS:
        c = counts.get(label, Counter())
        rows.append([label] + [c[v] for v in cols] + [sum(c.values())])
    rows.append(["total"] + [sum(counts[l][v] for l in counts) for v in cols] + [len(samples)])
    return table(["Label"] + cols + ["total"], rows)


def render(samples: list[Sample], sessions_count: int, splits: dict | None) -> str:
    subjects = {s.subject_id for s in samples}
    parts = [
        f"Generated by `python tools/dataset/stats.py` from {sessions_count} sessions, {len(subjects)} subjects, {len(samples)} samples. Do not edit this section by hand.",
        "",
        "### By label",
        "",
    ]
    by_label = Counter(s.label for s in samples)
    labeled = sum(1 for s in samples if s.meta.get("labelFinal"))
    parts.append(
        table(
            ["Label", "Samples", "Subjects", "Sessions"],
            [
                [
                    label,
                    by_label[label],
                    len({s.subject_id for s in samples if s.label == label}),
                    len({s.session_id for s in samples if s.label == label}),
                ]
                for label in LABELS
            ]
            + [["total", len(samples), len(subjects), len({s.session_id for s in samples})]],
        )
    )
    parts.append("")
    parts.append(f"Final labels assigned (labelFinal): {labeled}/{len(samples)}; the rest use the app's provisional label.")
    for title, key, values in DIMENSIONS:
        parts += ["", f"### {title}", "", cross(samples, key, values)]
    if splits:
        parts += ["", "### By split (splits.json)", ""]
        by_sample = splits.get("bySample", {})
        rows: list[list[object]] = []
        for label in LABELS:
            row: list[object] = [label]
            for sp in SPLITS:
                row.append(sum(1 for s in samples if s.label == label and by_sample.get(s.id) == sp))
            rows.append(row)
        rows.append(["total"] + [splits.get(sp, {}).get("samples", 0) for sp in SPLITS])
        rows.append(["subjects"] + [len(splits.get(sp, {}).get("subjects", [])) for sp in SPLITS])
        rows.append(["sessions"] + [len(splits.get(sp, {}).get("sessions", [])) for sp in SPLITS])
        parts.append(table(["Label", *SPLITS], rows))
    return "\n".join(parts)


def write_doc(doc: Path, body: str) -> None:
    text = doc.read_text(encoding="utf-8")
    i = text.find(BEGIN)
    j = text.find(END)
    if i < 0 or j < 0 or j < i:
        raise SystemExit(f"{doc} is missing the markers {BEGIN} … {END}")
    doc.write_text(text[:i] + BEGIN + "\n" + body + "\n" + text[j:], encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    utf8_console()
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("root", type=Path)
    p.add_argument("--splits", type=Path)
    p.add_argument("--doc", type=Path)
    args = p.parse_args(argv)
    sessions = load_root(args.root)
    samples = all_samples(sessions)
    splits_path = args.splits or (args.root / "splits.json")
    splits = read_json(splits_path) if splits_path.exists() else None
    body = render(samples, len(sessions), splits)
    if args.doc:
        write_doc(args.doc, body)
        print(f"wrote {args.doc}: {len(samples)} samples")
    else:
        print(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
